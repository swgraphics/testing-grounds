import assert from "node:assert/strict";
import { createServer } from "vite";
const server = await createServer({ configFile: false, cacheDir: "node_modules/.vite-tg-tests", optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, watch: null }, appType: "custom" });
globalThis.window = new EventTarget();
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, String(value)), removeItem: key => storage.delete(key) };
try {
  const { useWorldStore: world } = await server.ssrLoadModule("/src/systems/world/worldStore.js");
  const { useHistoryStore: history } = await server.ssrLoadModule("/src/systems/history/historyStore.js");
  const { treePropertyValue, mergeTreeProperties } = await server.ssrLoadModule("/src/systems/objects/treeProperties.js");
  const { resolveObjectTarget, editObjectTarget } = await server.ssrLoadModule("/src/systems/objects/objectEditing.js");
  const { saveWorldSnapshot, loadWorldSnapshot } = await server.ssrLoadModule("/src/systems/world/worldPersistence.js");
  world.getState().initializeBlankWorld();
  const chunkId = world.getState().world.currentChunkId;
  const legacy = { trunk: { height: 0 }, branches: { secondary: { count: 0 }, overrides: { 2: { length: 0 } } }, leaves: { color: "#ff0000", gradientColor: "#123456", gradientEnabled: false, floating: { enabled: false, density: 0 } } };
  assert.equal(treePropertyValue(legacy, "trunk.height"), 0);
  assert.equal(treePropertyValue(legacy, "branches.secondary.count"), 0);
  assert.equal(treePropertyValue(legacy, "leaves.floating.density"), 0);
  assert.equal(treePropertyValue({}, "branches.secondary.count"), 2);
  const merged = mergeTreeProperties(legacy, { leaves: { gradientEnabled: true } });
  assert.equal(merged.trunk, legacy.trunk, "unrelated sections retain identity");
  assert.equal(merged.branches, legacy.branches);
  assert.equal(merged.leaves.color, "#ff0000");
  assert.equal(merged.leaves.floating.enabled, false);
  assert.equal(merged.leaves.floating.density, 0);
  world.getState().upsertObject({ id: "tree-a", name: "Tree A", type: "procedural", modelType: "crimson-tree", treeDefinition: legacy, position: [1, 2, 3], rotationY: 0, scale: 1 });
  const target = { id: "tree-a", chunkId };
  editObjectTarget(target, { treeDefinition: { leaves: { color: "#2244ee", gradientEnabled: true } } });
  assert.equal(resolveObjectTarget(target).treeDefinition.leaves.color, "#2244ee");
  assert.equal(resolveObjectTarget(target).treeDefinition.trunk.height, 0);
  assert.equal(resolveObjectTarget(target).treeDefinition.branches.secondary.count, 0);
  assert.equal(resolveObjectTarget(target).treeDefinition.leaves.floating.enabled, false);
  history.getState().undo(); assert.equal(resolveObjectTarget(target).treeDefinition.leaves.color, "#ff0000");
  history.getState().redo(); assert.equal(resolveObjectTarget(target).treeDefinition.leaves.color, "#2244ee");
  editObjectTarget(target, { position: [5, 2, 7], rotationY: Math.PI / 4, scale: 1.4 });
  assert.deepEqual(resolveObjectTarget(target).position, [5, 2, 7]);
  history.getState().undo(); assert.deepEqual(resolveObjectTarget(target).position, [1, 2, 3]);
  history.getState().redo(); assert.equal(resolveObjectTarget(target).scale, 1.4);
  saveWorldSnapshot(); editObjectTarget(target, { scale: 2 }); loadWorldSnapshot();
  assert.equal(resolveObjectTarget(target).scale, 1.4);
  assert.equal(resolveObjectTarget(target).treeDefinition.leaves.color, "#2244ee");
  assert.equal(resolveObjectTarget({ id: "missing" }), null);
  console.log("PASS shared tree defaults/zero/legacy palette/structural identity; same-object edits, transform Undo/Redo and saved-world round-trip");
  const { addObjectToScatter, scatterEligibility } = await server.ssrLoadModule("/src/systems/objects/scatterOperations.js");
  const mesh = { id: "qa-population", name: "QA TREE", modelType: "crimson-tree", treeDefinition: legacy, source: "saved" };
  assert.equal(scatterEligibility(mesh).eligible, true);
  assert.equal(scatterEligibility({ id: "nature", modelPath: "/existing-model.gltf" }).eligible, true);
  assert.equal(scatterEligibility({ id: "upload", source: "uploaded", file: {} }).eligible, false);
  assert.equal(scatterEligibility({ id: "block", modelType: "building-block" }).eligible, false);
  const beforeIneligible = JSON.stringify(world.getState().world.scatterProfiles);
  assert.equal(addObjectToScatter({ id: "upload", source: "uploaded" }).ok, false);
  assert.equal(JSON.stringify(world.getState().world.scatterProfiles), beforeIneligible);
  addObjectToScatter(mesh);
  const first = structuredClone(world.getState().world.scatterProfiles[mesh.id]);
  history.getState().undo(); assert.equal(world.getState().world.scatterProfiles[mesh.id], undefined);
  history.getState().redo(); assert.deepEqual(world.getState().world.scatterProfiles[mesh.id], first);
  world.getState().upsertScatterProfile(mesh.id, { density: 0, coverage: 0, scaleVariation: 0, treeOverrides: { legacy: { leaves: { color: "#ff3300" } } } });
  addObjectToScatter(mesh);
  const retained = world.getState().world.scatterProfiles[mesh.id];
  assert.equal(retained.density, 0); assert.equal(retained.coverage, 0); assert.equal(retained.scaleVariation, 0);
  assert.equal(retained.treeOverrides.legacy.leaves.color, "#ff3300");
  saveWorldSnapshot(); world.getState().removeScatterProfile(mesh.id); loadWorldSnapshot();
  assert.deepEqual(world.getState().world.scatterProfiles[mesh.id], retained);
  console.log("PASS one population operation, eligibility feedback, no unsupported mutations, Add Undo/Redo, zero/override retention and population save/load");
} finally { await server.close(); delete globalThis.window; delete globalThis.localStorage; }
